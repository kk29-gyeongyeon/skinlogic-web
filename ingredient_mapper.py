def extract_standard_ingredients(ingredients_text: str) -> List[str]:
    """전성분 텍스트에서 50대 핵심 표준 활성 성분 추출 및 중복 제거"""
    if not ingredients_text:
        return []

    text_lower = str(ingredients_text).lower()
    matched = set()
    for alias, std_name in INGREDIENT_ALIAS_MAP.items():
        if alias in text_lower:
            matched.add(std_name)
    return sorted(list(matched))

def map_for_cpp_engine(raw_ingredients: List[str]) -> List[str]:
    """C++ 해시 상극 엔진 호환용 표준 키워드 치환"""
    transformed = []
    for ing in raw_ingredients:
        ing_clean = ing.strip()
        ing_lower = ing_clean.lower()
        matched = False
        for alias, std_name in INGREDIENT_ALIAS_MAP.items():
            if alias in ing_lower:
                transformed.append(std_name)
                matched = True
                break
        if not matched:
            transformed.append(ing_clean)
    return list(dict.fromkeys(transformed))